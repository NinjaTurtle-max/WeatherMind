"""표현 톤 문말 변환 — `effective_tone`의 **첫 소비처** (MT-11 최소 착지).

## 왜 이 파일이 생겼나 — 파이프의 빈 가운데

`users.tone` 축은 양 끝이 이미 서 있었다: 컬럼·CHECK 제약(0012 마이그레이션) ·
파생표(`weatherbrain_service.LEVEL_GROUP_TONE`) · 파생 함수(`effective_tone`) ·
API 노출(`GET /progress/me`의 `tone`). **그런데 그 값을 읽어 무언가를 바꾸는
소비처가 0곳이었다**(2026-08-18 조사 `docs/design/research/RESEARCH_MT8_10_11_DIFFICULTY.md`
§1.4 — `effective_tone`의 호출처가 `routers/progress.py` 하나뿐이고 용도는
"응답에 실어 보내기"였다). 즉 학령별 톤이 **계산은 되는데 아무도 안 썼다**.

그래서 조사 문서 §1.4가 지목한 그대로 — 「writer 0」을 고쳐도(가입 화면에 톤
선택을 붙여도) 화면의 문장은 한 글자도 안 바뀐다. 바꿔야 할 것은 **적용**이다.
이 모듈이 그 적용이고, 호출은 `answer_service.build_feedback`의 **사람 저작 해설
갈래 한 곳**뿐이다.

`ai-worker/app/chains/quiz_gen_chain.py:82-84`의 프롬프트 규칙 5가 저작 기준선을
teen(한다체) **한 벌**로 고정하면서 *"어린이·성인 말투는 런타임의 결정적 어미
치환이 담당한다"*고 적어 두었는데, **그 치환기가 저장소에 없었다**(대장 CO-Y-6이
2026-08-10에 처음 적고 54커밋 뒤에도 부재). 이 파일이 그 자리다 — 다만 **어린이
방향만** 채운다(성인 방향은 미착수, 아래 「범위 밖」).

## 무엇을 하는가 — `~다` → `~답니다`

한다체를 **해요체**로 바꾸는 것이 첫 후보였고 **버렸다.** 해요체 어미는 어간을
활용해야 해서 불규칙이 정면으로 나온다(`부른다 → 불러요`(르 불규칙) ·
`만든다 → 만들어요`(ㄹ 탈락) · `덥다 → 더워요`(ㅂ 불규칙)). 결정적 치환기가
어간을 건드리면 **오변환이 학습자 화면에 직접 나간다** — 조사 문서 §4.3이 (i)의
위험으로 지목한 바로 그것이다.

`~답니다`(부드러운 설명체 — 아동 도서의 그 어투)는 **어간을 건드리지 않는다.**
문말의 `다` 한 글자만 `답니다`로 갈면 되고, 활용이 이미 끝난 형태를 그대로 쓴다:

    한다 → 한답니다      부른다 → 부른답니다    만든다 → 만든답니다
    있다 → 있답니다      덥다  → 덥답니다      되었다 → 되었답니다

**유일한 위험 부류는 「받침 없는 음절 + 다」**다. 거기서 두 갈래가 갈리는데
문자열만 보고는 구분할 수 없다:

    형용사/동사:  다르다 → 다르답니다  (`답니다`가 맞다)
    명사 + 서술격: 하나다 → 하나랍니다  (`랍니다`가 맞다 — `답니다`면 틀린다)

그래서 **받침 있는 음절 뒤의 `다`만** 바꾼다. 받침 있는 명사는 국어에서 서술격
`이다`를 요구하므로(`값이다`이지 `값다`가 아니다) 받침이 있으면 명사 갈래가
원천적으로 배제된다 — 이 비대칭이 규칙을 안전하게 만드는 근거다. `이다`로 끝나는
문장은 별도로 `이랍니다`(규칙적)로 처리한다.

받침 없는 `다`는 **바꾸지 않는다.** 2026-08-18 시드 실측으로 초등 밴드(kl 1~2)
해설에서 이 부류에 걸린 실제 꼬리는 `다르다`·`크다`·`안전하다` 같은 형용사와
`홍수다`·`사례다`·`하나다`·`30%다` 같은 명사가 **섞여 있었다.** 섞여 있다는 것이
곧 규칙으로 못 가른다는 증거다.

이 보수성의 값: 초등 해설 198건 중 **117건(59%)이 바뀌고 81건은 원문으로 남는다**
(2026-08-19 실측 · 소유자는 `database/seed/content_items.json`). 남는 41%를 줄이려면
`답니다`/`랍니다` 판별을 사람이 정하거나 그 문항을 다시 저작해야 한다 — 둘 다
이 착지의 범위 밖이다. 변환 결과 **224문장을 전수 눈검사했고 오변환 0건**이다
(2026-08-19). 게이트가 어미만 보므로 이 눈검사가 문법을 보는 유일한 층이었다.

## 전부-아니면-전무 (섞인 어투를 만들지 않는다)

한 해설 안에서 어떤 문장은 바뀌고 어떤 문장은 안 바뀌면 `~답니다.` 와 `~한다.`가
한 문단에 섞인다. 그건 원문보다 **나쁘다.** 그래서 해설 안의 비존댓 문장 중
**하나라도** 변환 불가면 **그 해설 전체를 원문 그대로** 돌려준다(= 오늘의 동작,
회귀 0). 불변식은 한 줄로 적힌다: **출력에 원문 한다체와 변환문이 공존하지 않는다.**

⚠️ **존댓 판별 자체에 맹점이 하나 있다** — `_POLITE`가 `니다$`를 무는데 한다체
`아니다`가 거기 걸려 「이미 존댓말」로 **오분류**된다. 오분류는 스킵이 아니라
통과라서, 전부-아니면-전무를 **우회해 섞인 어투를 통과시킨다**(`~답니다.` 옆에
`~아니다.`). 그래서 `아니다`만 존댓 판별보다 **먼저** 본다. 오라클(계약 테스트)이
같은 정규식을 쓰므로 그쪽에도 같은 배제를 따로 넣어야 맹점이 공유되지 않는다.

이미 존댓말인 문장(`요`·`니다`·`니까`·`시오`·`세요`로 끝남)은 건드리지 않는다.
시드는 한다체·존댓·명령이 혼재하므로(조사 §2.2) 한다체 입력을 가정한 치환기가
존댓 문장을 깨는 것이 CO-Y-7이 경고한 순서 의존성이었다 — 여기서는 문장마다
입력 톤을 먼저 판별해 그 함정을 피한다. 존댓과 `답니다`는 한 문단에 자연스럽게
공존하므로 이 둘의 혼재는 위 불변식이 금하는 「섞임」이 아니다.

멱등이다: 출력이 `답니다`/`랍니다`로 끝나면 그 문장은 다음 회차에 존댓으로
분류돼 통과한다.

## 범위 밖 (의도적으로 안 한 것)

- **`question_text`** — 문말 빈칸 cloze(`… 기온이 ___.`)가 있어 변환기가 침범하고,
  `correct_answer`와 의미상 짝이라 정답 판정 문맥을 흔들 수 있다(조사 §4.3 (ii)).
- **채점 관련 필드 전부** — `correct_answer`·`options`·`pairs`·`items`는 문자열
  자체가 정답이다(조사 §4.1). 이 모듈은 그 필드를 **보지도 않는다**.
- **board 판정 문구·RAG 폴백** — `build_feedback`의 다른 두 갈래는 그대로 둔다.
- **child 외 톤** — `teen`·`adult`는 입력을 그대로 돌려준다. 학령과 무관한
  전역 문구 변경을 만들지 않는 것이 이 착지의 전제다.
"""

from __future__ import annotations

import re

# `weatherbrain_service.TONES`의 어린이 톤. 이 모듈은 의존을 만들지 않으려고
# 값을 복제하되, 어긋나면 `test_child_tone_feedback.py`가 운다(드리프트 감시는
# 사람이 아니라 계약 테스트가 한다 — CLAUDE.md §0-3).
CHILD_TONE = "child"

# 이미 존댓말인 문장 — 조사 문서 §2.2의 분류기와 **같은 식**을 쓴다(재현 가능하게
# 문서에 박혀 있는 그 정규식이다). 여기서는 "건드리지 않을 문장"의 판별에 쓴다.
_POLITE = re.compile(r"(요|니다|니까|시오|세요)$")

# 문장 분리 — 구분자를 캡처해 되붙인다(원문 공백·줄바꿈을 잃지 않는다).
_SENTENCE_SPLIT = re.compile(r"(?<=[.!?])(\s+)")

# 문장 = 본문 + 꼬리(구두점·닫는 따옴표·줄임표). 꼬리를 최대로 떼고 본문의
# 마지막 글자로 판정한 뒤 꼬리를 그대로 되붙인다.
_TAIL = re.compile(r"^(.*?)([\s.!?~'\"”’)…]*)$", re.DOTALL)

_HANGUL_START = 0xAC00
_HANGUL_END = 0xD7A3
_JONGSEONG_COUNT = 28


def has_batchim(char: str) -> bool:
    """한글 음절에 받침(종성)이 있는가 — 그 외 문자는 False.

    유니코드 한글 음절은 `초성×21×28 + 중성×28 + 종성` 구조라 종성 인덱스는
    코드포인트를 28로 나눈 나머지다(0 = 받침 없음).
    """
    code = ord(char)
    if not _HANGUL_START <= code <= _HANGUL_END:
        return False
    return (code - _HANGUL_START) % _JONGSEONG_COUNT != 0


def soften_sentence(core: str) -> str | None:
    """문장 본문(꼬리 제거분) 하나를 어린이 어투로 — 불가면 `None`.

    `None`은 "이 문장은 못 바꾼다"는 신호이고, 호출자는 그때 **해설 전체를**
    포기한다(섞인 어투 금지). 반환값이 입력과 같을 수 있다(이미 존댓말) —
    그건 실패가 아니다.
    """
    if not core:
        return core
    # ⚠️ `아니다`는 **존댓 판별보다 먼저** 본다. `_POLITE`가 `니다$`를 무는데
    # `아니다`는 한다체인데도 그 패턴에 걸려 「이미 존댓말」로 오분류된다. 그러면
    # 그 문장만 원문으로 남아 `~답니다.` 옆에 `~아니다.`가 서고 — 전부-아니면-전무가
    # 막으려던 **섞인 어투가 정확히 통과한다**(오분류라 스킵도 안 걸린다).
    # 시드 실측(2026-08-19)으로 초등 밴드에는 0건이지만 다른 밴드에 9건 있고,
    # R13 이후 저작이 한다체라 "~가 아니다"는 앞으로 늘어나는 어미다.
    # (`아닙니다`는 `닙니다`로 끝나므로 이 분기에 안 걸린다 — 진짜 존댓은 안전하다.)
    if core.endswith("아니다"):
        return core[:-3] + "아니랍니다"
    if _POLITE.search(core):
        return core
    if core.endswith("이다"):
        return core[:-2] + "이랍니다"
    if core.endswith("다") and len(core) >= 2 and has_batchim(core[-2]):
        return core[:-1] + "답니다"
    return None


def soften_for_tone(text: str, tone: str) -> str:
    """표현 톤에 맞춘 해설 문말 — `child`가 아니면 **입력 그대로**.

    child일 때만, 그리고 해설의 모든 문장이 변환 가능할 때만 바뀐다. 그 외에는
    바이트 동일하게 돌려준다(이 함수를 거쳐도 오늘의 동작이 보존된다).
    """
    if tone != CHILD_TONE or not text:
        return text

    pieces = _SENTENCE_SPLIT.split(text)
    out = list(pieces)
    changed = False
    for index in range(0, len(pieces), 2):  # 홀수 인덱스는 캡처된 구분자다
        matched = _TAIL.match(pieces[index])
        if matched is None:  # pragma: no cover - 두 그룹 모두 *라 항상 매치된다
            return text
        core, tail = matched.group(1), matched.group(2)
        softened = soften_sentence(core)
        if softened is None:
            return text  # 전부-아니면-전무
        if softened != core:
            changed = True
        out[index] = softened + tail
    return "".join(out) if changed else text
