/**
 * 유닛 노드 아이콘 — **규칙의 단일 소유자** (2026-08-19 결함 ⑪-a).
 *
 * ## 왜 이 파일이 생겼나
 *
 * 큰 화면과 작은 화면이 **다른 규칙**을 쓰고 있었다. 같은 순간·같은 유닛인데:
 *
 * | 경로 | 아이콘 분포 |
 * |---|---|
 * | PC(`PcCurriculumPath`) | `🌀 1 · ⭐ 1` — **개념 구분 없음** |
 * | 모바일(`CurriculumHome`) | `👑 · 🧊 · 🌀 · 🌪 · ⚡` — 개념별 |
 *
 * PC가 `STATUS_ICON[status] ?? '🌀'`로 **개념 아이콘을 상태 아이콘으로 덮어썼다.**
 * 열린 유닛이 많아질수록 화면이 **회오리 도배**가 된다. 클라이언트 지적:
 * *"이모티콘이 해상도 사이즈 따라 짤리네, 크면 다 회오리로"*.
 *
 * ⚠️ **드러난 계기가 우리 수정이다.** ⑧⑨(배치 선해제를 시작 위치로 전파)로
 * 수십~수백 유닛이 열리면서, 종전에 🔒로 덮여 있던 자리가 전부 드러났다.
 * 결함은 원래 있었고 **잠금이 가려 주고 있었다.**
 *
 * ## 🔴 어느 쪽이 원본인가 — **모바일이다**
 *
 * 옮긴 것은 `CurriculumHome`의 규칙이고 **PC가 그것을 따라온 것**이다. PC가 틀린
 * 이유는 「상태」와 「개념」이 **다른 축인데 한 칸에 밀어 넣었기** 때문이다 —
 * 상태는 4값(cleared·current·unlocked·locked)이고 개념은 14값이라, 상태로 덮으면
 * **개념 정보가 통째로 사라진다.** 반대로 개념으로 덮으면 「어디까지 했나」가
 * 사라지므로, 정답은 **어느 한쪽이 아니라 자리별로 갈라 쓰는 것**이다(아래).
 *
 * ⚠️ **PC 규칙이 더 단순해 보인다고 되돌리지 말 것.** 단순한 것이 아니라
 * **정보를 버린 것**이다. 이 문단이 그 판단의 근거다.
 *
 * ## 규칙
 *
 * | 상태 | 아이콘 | 왜 |
 * |---|---|---|
 * | `cleared` | 👑 | **상태가 더 중요하다** — 왕관은 보상이고 한눈에 세어야 한다 |
 * | `locked` | 🔒 | 상태가 더 중요하다 — 못 들어간다는 것이 먼저다 |
 * | `current` | ⭐ | 상태가 더 중요하다 — **지금 여기**가 화면에서 하나뿐이다 |
 * | `unlocked` | **개념 아이콘** | 열린 것은 **여러 개**다. 상태로 덮으면 서로 구별이 안 되고, 학습자가 고를 근거를 잃는다 |
 *
 * 개념 표는 `CONCEPT_ICON` 하나가 소유한다(표시명은 `concept.*` i18n 리소스 몫이라
 * 여기엔 아이콘만 둔다). 캐릭터 배정(`conceptCharacter.js`)과 짝을 맞춘다 — 짝이
 * 어긋나면 **같은 개념이 유닛 노드와 능력 분석에서 다른 얼굴**로 보인다.
 */

// 기초과학 6종은 2026-08-08 추가. 그 전에는 표에 없어 전부 폴백('📘')이라
// 기초과학 코스의 유닛 노드가 죄다 같은 책 아이콘이었다.
export const CONCEPT_ICON = {
  // 날씨 코스(weather)
  pressure_front: '🌀',
  typhoon: '🌪️',
  air_mass: '🧊',
  heat_island: '🏙️',
  co2_climate: '🌡️',
  anomaly: '⚡',
  // 기초과학 코스(basic-science)
  temperature_heat: '🌡️',
  // 2026-08-18 — 캐릭터가 sun → grass, cloud → wind로 바뀌어 아이콘도 함께 옮겼다.
  radiation_budget: '🌿',
  pressure_basics: '💨',
  density_buoyancy: '🌈',
  phase_change: '💧',
  energy_transfer: '🌙',
  // 재난 축 2종 — 표에 없어 폴백('📘')으로 떨어져 있었다(2026-08-18에 발견).
  wildfire_weather: '🔥',
  flood_response: '🌊',
};

/** 개념 태그 → 아이콘. 미등재 태그는 책으로 떨어진다(못 그리는 것보다 낫다). */
export const conceptIcon = (conceptTag) => CONCEPT_ICON[conceptTag] ?? '📘';

/**
 * **상태가 이기는 자리**만 여기 있다. `unlocked`가 없는 것이 이 표의 요점이다 —
 * 열린 유닛은 개념으로 구별해야 하므로 상태 아이콘을 주지 않는다.
 */
const STATUS_WINS = { cleared: '👑', current: '⭐', locked: '🔒' };

/**
 * 유닛 노드에 그릴 아이콘 하나 — **두 화면이 이 함수만 부른다.**
 *
 * `status`가 없거나 모르는 값이면 개념 아이콘으로 떨어진다. 폴백을 상태 쪽이 아니라
 * 개념 쪽으로 둔 이유: **모르는 상태를 🌀로 덮으면 결함이 다시 회오리 도배로
 * 나타난다.** 개념으로 떨어지면 최소한 유닛끼리 구별은 된다.
 */
export function unitIcon(unit, status) {
  return STATUS_WINS[status] ?? conceptIcon(unit?.concept_tag);
}
