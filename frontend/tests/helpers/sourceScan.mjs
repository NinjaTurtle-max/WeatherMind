/**
 * 소스 계약 스캔 공용 도구 — **테스트가 아니다**(`*.test.mjs`가 아니므로 ci.sh의
 * FRONT_TESTS가 집지 않는다). 여러 스모크가 같은 실수를 반복해서 여기로 모았다.
 *
 * 🔴 **「없다」를 물을 때는 주석을 걷고 본다.**
 *
 * 소스 계약 여럿이 「이 낱말이 코드에 **없어야** 한다」는 꼴인데, 그 결정을
 * 설명하는 주석에는 바로 그 낱말이 들어간다 — "「다시 도전」으로 푸는 길은
 * 없다"처럼. 원본을 그대로 훑으면 두 방향으로 다 틀린다:
 *  · **자기 주석에 걸려** 영원히 붉다(hindcast의 잠금 계약에서 실제로 그랬다)
 *  · 반대로 값을 되살려도 **주석이 남아 조용히 통과**한다(탐정 실 색 계약에서
 *    `#B8443C`가 내 주석 안에 있어 통과했다 — 돌연변이 검증으로 발견)
 *
 * ⚠️ 「있다」를 묻는 계약도 그림·부품 이름처럼 **주석에 이름이 적히는** 것이면
 * 같이 걷어야 한다. 지워도 주석이 남아 통과하기 때문이다.
 *
 * ⚠️ 정규식 기반이라 문자열 리터럴 안의 `//`·`/*` 는 구분하지 못한다. 계약이
 * 그런 문자열을 겨냥한다면 이 함수를 쓰지 말고 원본을 볼 것.
 */
export function codeOnly(src) {
  return src
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '') // JSX 주석
    .replace(/\/\*[\s\S]*?\*\//g, '') // 블록 주석
    .replace(/^\s*\/\/.*$/gm, ''); // 줄 주석
}
